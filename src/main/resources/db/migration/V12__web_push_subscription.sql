-- 웹 푸시 구독 (브라우저·기기마다 1건, 한 유저가 여러 기기 가능)
-- endpoint 는 브라우저 푸시 서버 주소라 기기마다 다름 -> UNIQUE.
-- 같은 기기에서 다른 계정으로 로그인해 다시 등록하면 user_id 만 새 계정으로 바뀜 (이전 계정 알림이 그 기기에 가지 않게)
CREATE TABLE push_subscription (
    push_subscription_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint        NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    endpoint        varchar(1024) NOT NULL,
    p256dh          varchar(120)  NOT NULL,
    auth            varchar(40)   NOT NULL,
    user_agent      varchar(200),
    failure_count   integer       NOT NULL DEFAULT 0, -- 연속 실패 (일시 오류). 성공하면 0
    last_success_dt timestamp(6),
    create_dt       timestamp(6)  NOT NULL,
    update_dt       timestamp(6)  NOT NULL,
    CONSTRAINT uk_push_subscription_endpoint UNIQUE (endpoint)
);
CREATE INDEX idx_push_subscription_user ON push_subscription (user_id);
