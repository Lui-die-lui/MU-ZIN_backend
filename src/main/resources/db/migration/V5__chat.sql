-- 수강생 <-> 아티스트 1:1 채팅 (2026-10-18)
-- 방 = 수강생 1명 + 아티스트 1명 (아티스트가 처음 예약을 수락할 때 생성)
-- 채팅 가능 여부는 저장하지 않고 예약 기록으로 계산 (진행 중 확정 예약 또는 마지막 완료 레슨 후 14일 이내)

CREATE TABLE chat_room (
    chat_room_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             bigint       NOT NULL REFERENCES users (user_id),
    artist_profile_id   bigint       NOT NULL REFERENCES artist_profile (artist_profile_id),
    student_last_read_id bigint,
    artist_last_read_id  bigint,
    last_message_id     bigint,
    last_message_dt     timestamp(6),
    create_dt           timestamp(6) NOT NULL,
    update_dt           timestamp(6),
    CONSTRAINT uk_chat_room_pair UNIQUE (user_id, artist_profile_id)
);
CREATE INDEX idx_chat_room_artist ON chat_room (artist_profile_id);

CREATE TABLE chat_message (
    chat_message_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_room_id    bigint        NOT NULL REFERENCES chat_room (chat_room_id),
    sender_user_id  bigint        NOT NULL REFERENCES users (user_id),
    content         varchar(1000) NOT NULL,
    create_dt       timestamp(6)  NOT NULL,
    update_dt       timestamp(6)
);
CREATE INDEX idx_chat_message_room ON chat_message (chat_room_id, chat_message_id);

-- 이미 수락된 적이 있는 수강생·아티스트 쌍은 방을 미리 만들어 둠
INSERT INTO chat_room (user_id, artist_profile_id, create_dt)
SELECT DISTINCT r.user_id, l.artist_profile_id, (now() AT TIME ZONE 'Asia/Seoul')
FROM lesson_reservation r
JOIN lessons l ON l.lesson_id = r.lesson_id
WHERE r.status IN ('CONFIRMED', 'COMPLETION_PENDING', 'COMPLETED')
ON CONFLICT ON CONSTRAINT uk_chat_room_pair DO NOTHING;
