-- 이용약관 · 개인정보 수집·이용 · 만 14세 이상 동의 기록 (약관이 바뀌어 다시 동의하면 새 행 추가 - 이력 유지)
CREATE TABLE user_consent (
    consent_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint       NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    terms_version   varchar(20)  NOT NULL,
    privacy_version varchar(20)  NOT NULL,
    age_over_14     boolean      NOT NULL,
    agreed_dt       timestamp(6) NOT NULL
);
CREATE INDEX idx_user_consent_user ON user_consent (user_id, agreed_dt);

