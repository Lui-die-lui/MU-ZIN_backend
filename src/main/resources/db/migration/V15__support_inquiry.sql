-- 운영자 문의 (2026-11-14)
-- 로그인한 사용자가 운영자에게 묻고, 관리자가 답변 1개. 첨부 없음

CREATE TABLE support_inquiry (
    support_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint        NOT NULL REFERENCES users (user_id),
    category       varchar(20)   NOT NULL CHECK (category IN ('ACCOUNT', 'RESERVATION', 'REPORT', 'BUG', 'ETC')),
    content        varchar(2000) NOT NULL,
    status         varchar(20)   NOT NULL CHECK (status IN ('OPEN', 'ANSWERED')),
    reply_content  varchar(2000),
    replied_dt     timestamp(6),
    replied_by     bigint REFERENCES users (user_id),
    create_dt      timestamp(6)  NOT NULL,
    update_dt      timestamp(6)
);
CREATE INDEX idx_support_inquiry_status ON support_inquiry (status, create_dt);
CREATE INDEX idx_support_inquiry_user ON support_inquiry (user_id, create_dt);

-- 알림 종류: 새 운영자 문의(-> 관리자) / 답변(-> 문의한 사람)
ALTER TABLE notification DROP CONSTRAINT IF EXISTS notification_type_check;
ALTER TABLE notification ADD CONSTRAINT notification_type_check
    CHECK (type IN ('RESERVATION_REQUESTED', 'RESERVATION_CONFIRMED', 'RESERVATION_REJECTED',
                    'RESERVATION_COMPLETION_PENDING', 'RESERVATION_COMPLETED',
                    'RESERVATION_CANCELED_BY_USER', 'RESERVATION_CANCELED_BY_ARTIST',
                    'RESERVATION_EXPIRED', 'REVIEW_CREATED', 'REVIEW_REPLIED',
                    'INQUIRY_CREATED', 'INQUIRY_REPLIED', 'INQUIRY_TO_CHAT',
                    'ARTIST_APPROVED', 'ARTIST_REJECTED',
                    'SUPPORT_CREATED', 'SUPPORT_REPLIED'));
ALTER TABLE notification DROP CONSTRAINT IF EXISTS notification_ref_type_check;
ALTER TABLE notification ADD CONSTRAINT notification_ref_type_check
    CHECK (ref_type IN ('RESERVATION', 'CHAT_ROOM', 'REVIEW', 'INQUIRY', 'SUPPORT'));
