-- 관리자 대시보드(방문·유입) + 이상행동 감지 + 신고

-- 방문 기록: 브라우저별 임의 ID 로 하루 1건 (IP·쿠키·회원 ID 저장 안 함)
CREATE TABLE site_visit (
    visit_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visitor_id    varchar(36)  NOT NULL,
    visit_date    date         NOT NULL,
    source        varchar(20)  NOT NULL CHECK (source IN ('DIRECT', 'SEARCH', 'SOCIAL', 'REFERRAL', 'CAMPAIGN')),
    referrer_host varchar(100),
    utm_source    varchar(50),
    landing_path  varchar(200),
    is_returning  boolean      NOT NULL DEFAULT false, -- 이전에 방문한 적 있는 브라우저
    create_dt     timestamp(6) NOT NULL,
    CONSTRAINT uk_site_visit_day UNIQUE (visitor_id, visit_date)
);
CREATE INDEX idx_site_visit_date ON site_visit (visit_date);

-- 로그인 실패 기록 (비밀번호 대입 감지용, 30일 뒤 삭제). 있는 계정이면 user_id 도 남김
CREATE TABLE login_failure_log (
    login_failure_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email            varchar(100) NOT NULL,
    user_id          bigint REFERENCES users (user_id) ON DELETE CASCADE,
    create_dt        timestamp(6) NOT NULL
);
CREATE INDEX idx_login_failure_dt ON login_failure_log (create_dt);
CREATE INDEX idx_login_failure_user ON login_failure_log (user_id, create_dt);

-- 예약을 누가 취소했는지 (반복 취소 감지용). 이전 취소는 알 수 없어서 null
ALTER TABLE lesson_reservation ADD COLUMN canceled_by varchar(10) CHECK (canceled_by IN ('USER', 'ARTIST'));
