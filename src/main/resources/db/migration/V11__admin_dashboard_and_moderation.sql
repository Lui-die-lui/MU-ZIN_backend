-- 채팅 도배 감지용 (보낸 사람 기준 최근 메시지)
CREATE INDEX idx_chat_message_sender ON chat_message (sender_user_id, create_dt);
CREATE INDEX idx_review_user ON review (review_user_id, create_dt);

-- 이상행동 감지 결과. 같은 유저·규칙은 열린 건이 하나만 (다시 걸리면 수치만 갱신)
CREATE TABLE abuse_flag (
    abuse_flag_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          bigint       NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    rule             varchar(30)  NOT NULL CHECK (rule IN ('CHAT_FLOOD', 'INQUIRY_SPAM', 'RESERVATION_SPAM',
                                                           'RESERVATION_CANCEL', 'LOGIN_FAILURE', 'REVIEW_BURST',
                                                           'REVIEW_LOW_RATING', 'REPORTED')),
    detail           varchar(255) NOT NULL,
    metric           integer      NOT NULL,
    status           varchar(20)  NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'DISMISSED', 'ACTIONED')),
    detected_dt      timestamp(6) NOT NULL,
    last_detected_dt timestamp(6) NOT NULL,
    resolved_by      bigint REFERENCES users (user_id) ON DELETE SET NULL,
    resolved_dt      timestamp(6)
);
CREATE UNIQUE INDEX uk_abuse_flag_open ON abuse_flag (user_id, rule) WHERE status = 'OPEN';
CREATE INDEX idx_abuse_flag_status ON abuse_flag (status, last_detected_dt);

-- 유저 신고. 신고 당시 내용을 남겨 둠 (나중에 수정·삭제돼도 관리자가 확인 가능)
CREATE TABLE user_report (
    report_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_user_id bigint        NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    target_user_id   bigint        NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    target_type      varchar(20)   NOT NULL CHECK (target_type IN ('ARTIST', 'CHAT_ROOM', 'REVIEW', 'INQUIRY')),
    target_ref_id    bigint        NOT NULL,
    reason           varchar(20)   NOT NULL CHECK (reason IN ('SPAM', 'ABUSE', 'FRAUD', 'INAPPROPRIATE', 'ETC')),
    detail           varchar(1000),
    content_snapshot text,
    status           varchar(20)   NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'DISMISSED', 'ACTIONED')),
    admin_memo       varchar(255),
    resolved_by      bigint REFERENCES users (user_id) ON DELETE SET NULL,
    resolved_dt      timestamp(6),
    create_dt        timestamp(6)  NOT NULL,
    CONSTRAINT uk_user_report_once UNIQUE (reporter_user_id, target_type, target_ref_id)
);
CREATE INDEX idx_user_report_status ON user_report (status, create_dt);
CREATE INDEX idx_user_report_target ON user_report (target_user_id, status);
