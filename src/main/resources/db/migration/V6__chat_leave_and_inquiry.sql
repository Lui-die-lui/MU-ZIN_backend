-- 2) 레슨 문의: 질문 1개 + 답변 1개, 아티스트가 원하면 채팅으로 넘김
CREATE TABLE lesson_inquiry (
    inquiry_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           bigint        NOT NULL REFERENCES users (user_id),
    artist_profile_id bigint        NOT NULL REFERENCES artist_profile (artist_profile_id),
    content           varchar(1000) NOT NULL,
    reply_content     varchar(1000),
    replied_dt        timestamp(6),
    status            varchar(20)   NOT NULL CHECK (status IN ('OPEN', 'REPLIED', 'CHAT')),
    chat_room_id      bigint REFERENCES chat_room (chat_room_id) ON DELETE SET NULL,
    create_dt         timestamp(6)  NOT NULL,
    update_dt         timestamp(6)
);
CREATE INDEX idx_lesson_inquiry_artist ON lesson_inquiry (artist_profile_id, create_dt);
CREATE INDEX idx_lesson_inquiry_user ON lesson_inquiry (user_id, create_dt);

