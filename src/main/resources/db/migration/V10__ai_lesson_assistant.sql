-- AI 레슨 내비게이터 (2026-10-19)
-- 로그인 사용자가 자연어로 레슨·아티스트를 찾는 도구 호출형 AI. 근거는 MU:ZIN DB 에서 조회 (벡터 검색 없음)
-- 사용량 제한은 Redis 없이 이 테이블들의 조건부 UPDATE(원자적)로 처리
-- 시각 컬럼은 다른 테이블과 같이 KST(Asia/Seoul) LocalDateTime

-- 1) 사용자별 주간 사용량: (user_id, week_start) 한 줄. week_start = KST 기준 그 주 월요일
--    스케줄러로 초기화하지 않음 -> 새 주가 되면 새 줄이 생김
CREATE TABLE ai_weekly_usage (
    user_id     bigint    NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    week_start  date      NOT NULL,
    used        integer   NOT NULL DEFAULT 0 CHECK (used >= 0),
    update_dt   timestamp NOT NULL,
    PRIMARY KEY (user_id, week_start)
);

-- 2) 대화
--    status: PROCESSING(첫 답변 만드는 중) / ACTIVE / CLOSED(질문 횟수 소진)
--    in_flight_until: 답변 처리 중 잠금 만료 시각 (null = 처리 중 아님). 만료되면 복구 작업이 정리
--    style_context: 사용자가 반영을 선택한 취향 진단 요약 (서버에서 검증한 값만)
CREATE TABLE ai_conversation (
    conversation_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             bigint       NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    week_start          date         NOT NULL,
    status              varchar(20)  NOT NULL CHECK (status IN ('PROCESSING', 'ACTIVE', 'CLOSED')),
    title               varchar(80)  NOT NULL,
    style_context       jsonb,
    user_message_count  integer      NOT NULL DEFAULT 0 CHECK (user_message_count >= 0),
    in_flight_until     timestamp,
    idempotency_key     varchar(64)  NOT NULL,
    create_dt           timestamp    NOT NULL,
    update_dt           timestamp    NOT NULL,
    CONSTRAINT uk_ai_conversation_idem UNIQUE (user_id, idempotency_key)
);
CREATE INDEX idx_ai_conversation_user ON ai_conversation (user_id, update_dt DESC);
CREATE INDEX idx_ai_conversation_inflight ON ai_conversation (in_flight_until) WHERE in_flight_until IS NOT NULL;
CREATE INDEX idx_ai_conversation_update ON ai_conversation (update_dt);

-- 3) 메시지
--    USER: 사용자 질문 (status PROCESSING -> OK, 실패하면 행을 지우고 횟수를 돌려줌)
--          reserved_micros = 이 질문 처리에 잡아 둔 예산 (정산 후 0)
--    ASSISTANT: 답변 + 서버가 검증한 추천 (id·종류·이유만 저장, 가격 등은 조회 시 DB 에서 다시 채움)
--    cost_status: EXACT(응답 usage 로 정산) / UNCERTAIN(호출 뒤 결과를 모름 -> 예약액으로 보수 정산)
CREATE TABLE ai_message (
    message_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id      bigint       NOT NULL REFERENCES ai_conversation (conversation_id) ON DELETE CASCADE,
    role                 varchar(10)  NOT NULL CHECK (role IN ('USER', 'ASSISTANT')),
    content              text         NOT NULL,
    recommendations      jsonb,
    status               varchar(20)  NOT NULL CHECK (status IN ('PROCESSING', 'OK')),
    idempotency_key      varchar(64),
    model                varchar(80),
    input_tokens         integer,
    cached_input_tokens  integer,
    output_tokens        integer,
    cost_micros          bigint,
    cost_status          varchar(20)  CHECK (cost_status IN ('EXACT', 'UNCERTAIN')),
    reserved_micros      bigint       NOT NULL DEFAULT 0 CHECK (reserved_micros >= 0),
    budget_key           varchar(40),  -- 예약한 월간 예산 행 (복구 시 같은 행을 정리)
    create_dt            timestamp    NOT NULL,
    CONSTRAINT uk_ai_message_idem UNIQUE (conversation_id, idempotency_key)
);
CREATE INDEX idx_ai_message_conversation ON ai_message (conversation_id, message_id);
CREATE INDEX idx_ai_message_processing ON ai_message (create_dt) WHERE status = 'PROCESSING';

-- 4) 월간 비용 (전역). budget_key = '<provider>:<KST yyyy-MM>' (예: openai:2026-10)
--    단위는 마이크로 USD 정수 (1 USD = 1,000,000)
--    호출 전 reserved 에 예상 최대 비용을 잡고(spent + reserved + 예상 <= cap 일 때만), 호출 뒤 실제 비용으로 옮김
--    uncertain_micros: spent 중 실제 청구 여부를 모르는 호출을 예약액으로 보수 계산한 부분 (spent 에 포함됨)
CREATE TABLE ai_monthly_budget (
    budget_key        varchar(40) PRIMARY KEY,
    cap_micros        bigint    NOT NULL CHECK (cap_micros >= 0),
    reserved_micros   bigint    NOT NULL DEFAULT 0 CHECK (reserved_micros >= 0),
    spent_micros      bigint    NOT NULL DEFAULT 0 CHECK (spent_micros >= 0),
    uncertain_micros  bigint    NOT NULL DEFAULT 0 CHECK (uncertain_micros >= 0),
    update_dt         timestamp NOT NULL
);
